// Generates custom_components/sofabaton_x1s/www/src/shared/x2-icons.ts from
// the drawings in scripts/x2-icons/icons.mjs: one minified 24x24 path per X2
// icon id. The output is committed; rerun after editing an icon
// (tests/frontend/x2-icons.test.ts fails while the two disagree).

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import * as B from "./x2-icons/geometry.mjs";
import { ICONS } from "./x2-icons/icons.mjs";

// fileURLToPath, not URL.pathname: the pathname is percent-encoded, which
// breaks checkouts whose path holds a space or non-ASCII characters.
const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = join(ROOT, "custom_components/sofabaton_x1s/www/src/shared/x2-icons.ts");

const entries = Object.entries(ICONS).map(([id, [name, draw]]) => `  // ${name}\n  ${id}: "${B.build(draw(B))}",`);

const source = `// GENERATED by scripts/build-x2-icons.mjs from scripts/x2-icons/icons.mjs. Do not edit by hand.
//
// The X2 activity/device icon set, keyed by the icon id an X2 entity record
// stores (1-${entries.length}). Each value is one path on a 24x24 viewBox with
// nonzero fill, the same contract as @mdi/js, so it renders through
// ha-svg-icon's \`path\` or a plain <svg viewBox="0 0 24 24"><path d="...">.
// The wordmarks (13-16, 35-45) belong to the services they name.

export const X2_ICON_PATHS: Readonly<Record<number, string>> = {
${entries.join("\n")}
};
`;

writeFileSync(OUT, source);
const bytes = Object.values(ICONS).reduce((n, [, draw]) => n + B.build(draw(B)).length, 0);
console.log(`wrote ${OUT} (${entries.length} icons, ${bytes} bytes of path data)`);
